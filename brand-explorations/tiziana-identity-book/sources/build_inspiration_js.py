"""Writes document-source/inspiration.js (moodboard selection) from photographies/inspiration/inspiration.json."""
import json
KEEP = ['stylo-1', 'carnet-1', 'interieur-beige-2', 'carnet-2', 'stylo-2', 'fauteuil-cuir-2']
meta = {m['key']: m for m in json.load(open('photographies/inspiration/inspiration.json'))}
sel = [meta[k] for k in KEEP if k in meta]
open('document-source/inspiration.js', 'w').write('/* generated by sources/build_inspiration_js.py — CC0 moodboard photographs */\nwindow.INSP = ' + json.dumps(sel, ensure_ascii=False, indent=1) + ';\n')
print(len(sel))
