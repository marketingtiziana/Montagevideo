"""Writes document-source/env-sources.js and sources/sources-photographiques.md from the CC0 metadata files."""
import json, os
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
USED = {'bureau-lumineux': 'texture verre dépoli (D) — floutée', 'colonnes-beton': 'publication internationale (D, H2)', 'facade-classique': 'cadre du décor B2', 'carnet-1': 'mains et objets (référence, pas Tiziana)'}
meta = {}
for f in ['photographies/environnements/index.json', 'photographies/environnements/inspiration.json']:
    if os.path.exists(f):
        for m in json.load(open(f)):
            k = (m.get('key') or os.path.basename(m['file']).rsplit('.', 1)[0])
            meta[k] = m
rows, md = [], ['# Sources photographiques', '', '## Photographies de Tiziana', '', 'Shooting réel (dossier Drive « 📸PHOTOS Tiziana »), 19 photos dans `photographies/tiziana/`. Détourages dans `photographies/detourages/`. Aucune retouche du visage ; seul l’étalonnage change selon la direction. Les décors sont des photomontages de simulation.', '', '## Environnements et références (CC0, via Openverse)', '', '| Fichier | Usage dans le livre | Titre | Auteur | Source | Page |', '|---|---|---|---|---|---|']
for k, m in sorted(meta.items()):
    use = USED.get(k, 'non utilisé dans le PDF')
    md.append(f"| {os.path.basename(m['file'])} | {use} | {m.get('title') or '—'} | {m.get('creator') or 'non crédité'} | {m.get('source')} | {m.get('page') or m.get('foreign_landing_url') or '—'} |")
    if k in USED:
        rows.append(f"{os.path.basename(m['file'])} — {use} — {m.get('creator') or 'auteur non crédité'}, {m.get('source')}, CC0")
md += ['', '## Rendus graphiques', '', 'Textures, objets, signes, décors et interfaces sont des rendus originaux générés par `document-source/`.', '']
open('sources/sources-photographiques.md', 'w').write('\n'.join(md))
open('document-source/env-sources.js', 'w').write('/* generated by sources/build_env_sources.py */\nwindow.ENV_SOURCES = ' + json.dumps(rows, ensure_ascii=False, indent=1) + ';\n')
print(len(rows), 'used /', len(meta))
