type Init = Omit<Partial<Content>, 'creative'> & Pick<Content, 'id' | 'subject' | 'format'> & { creative?: Partial<CreativeDirection> }

const now = Date.now()

function c(init: Init): Content {
  const brands = init.brands ?? (init.id.startsWith('TZ') ? ['TZ'] : init.id.startsWith('DB') ? ['FN', 'TZ'] : ['FN'])
  return {
    hook: '',
    problemIds: [],
    pillar: null,
    platforms: [],
    objective: null,
    angle: '',
    outline: '',
    script: '',
    cta: '',
    status: 'idee',
    validation: 'IDÉE À VALIDER',
    techValidation: 'non-requise',
    owner: '',
    publishDate: '',
    imageIds: [],
    relatedIds: [],
    notes: '',
    source: SRC.claude,
    creativeIsProposal: true,
    createdAt: now,
    updatedAt: now,
    ...init,
    brands,
    creative: { ...EMPTY_CREATIVE, ...(init.creative ?? {}) } as CreativeDirection,
  }
}

const blk = (title: string, body: string, level: 1 | 2 | 3 = 2): InfoBlock => ({ id: uid('b'), title, body, level })
const info = (title: string, blocks: InfoBlock[], dataHierarchy: string, composition: string): InfographicModel => ({
  title,
  blocks,
  dataHierarchy,
  composition,
  imageId: 'IMG-001',
})
const slide = (title: string, message: string, body: string, role: string, composition = '', imageId: string | null = null): Slide => ({
  id: uid('s'),
  title,
  message,
  body,
  role,
  composition,
  imageId,
})
const scr = (
  visual: string,
  text: string,
  typography: string,
  interaction = '',
  cta = '',
  textPosition = 'Haut gauche, marges de sécurité',
  imageId: string | null = null,
): StoryScreen => ({ id: uid('sc'), visual, text, typography, textPosition, interaction, cta, imageId })
const scene = (duration: string, image: string, dialogue: string, goal: string, extra: Partial<Scene> = {}): Scene => ({
  id: uid('sn'),
  duration,
  image,
  dialogue,
  camera: '',
  voiceover: '',
  transition: '',
  goal,
  imageId: null,
  ...extra,
})

